def _render_entries_module(
    entries: Sequence[Any], *, module_kind: str, fast_directions: Mapping[int, frozenset[str]]
) -> str:
    """Render one generated raw shard containing schema classes in deterministic order.

    Args:
        entries: Schema entries assigned to this shard.
        module_kind: Raw surface kind used for imports and base classes.
        fast_directions: Reviewed native fast-path directions by constructor ID.
    """
    base_class = "TLConstructor" if module_kind == "types" else "TLRequest"
    base_import = (
        "TLConstructor, TLField, TLFlagGroup"
        if base_class == "TLConstructor"
        else f"TLField, TLFlagGroup, {base_class}"
    )
    lines: list[str] = [
        _HEADER.rstrip(),
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Any, ClassVar, Self, cast",
        "",
        f"from miniproto.raw.base import {base_import}",
        "from miniproto.tl.codec import (",
        "    TLCodecError,",
        "    decode_bool,",
        "    decode_bytes,",
        "    decode_constructor_id,",
        "    decode_double,",
        "    decode_int,",
        "    decode_int128,",
        "    decode_int256,",
        "    decode_long,",
        "    decode_object,",
        "    decode_string,",
        "    decode_value,",
        "    decode_vector,",
        "    encode_bool,",
        "    encode_bytes,",
        "    encode_constructor_id,",
        "    encode_double,",
        "    encode_int,",
        "    encode_int128,",
        "    encode_int256,",
        "    encode_long,",
        "    encode_string,",
        "    encode_value,",
        "    encode_vector,",
        ")",
    ]
    if any(entry.constructor_id in fast_directions for entry in entries):
        lines.extend(["from miniproto.tl.fast import decode_fast, encode_fast, materialize_empty_object"])
    lines.extend(["", ""])
    for entry in entries:
        fields = iter_public_params(entry.params)
        lines.extend(
            ["@dataclass(frozen=True, slots=True, kw_only=True)", f"class {entry.python_class_name}({base_class}):"]
        )
        if fields:
            for field in fields:
                lines.append(_field_line(field))
        else:
            lines.append("    pass")
        lines.extend(
            [
                f"    CONSTRUCTOR_ID: ClassVar[int] = 0x{entry.constructor_id_hex}",
                f"    QUALNAME: ClassVar[str] = {entry.name!r}",
                f"    RESULT_TYPE: ClassVar[str] = {entry.result_type!r}",
                f"    TL_FIELDS: ClassVar[tuple[TLField, ...]] = {_fields_tuple(fields)}",
                f"    TL_FLAG_GROUPS: ClassVar[tuple[TLFlagGroup, ...]] = {_flag_groups_tuple(entry.params)}",
                "",
                *_codec_methods(
                    fields, entry.params, fast_directions=fast_directions.get(entry.constructor_id, frozenset())
                ),
                "",
                "",
            ]
        )
    all_class_names = [entry.python_class_name for entry in entries]
    namespace_lines, namespace_names = _namespace_classes(entries)
    lines.extend(namespace_lines)
    all_names = all_class_names + namespace_names + ["CONSTRUCTOR_ID_MAP", "NAME_MAP"]
    lines.append(f"ALL_{module_kind.upper()}: tuple[type[{base_class}], ...] = (")
    for name in all_class_names:
        lines.append(f"    {name},")
    lines.append(")")
    lines.append(
        f"CONSTRUCTOR_ID_MAP: dict[int, type[{base_class}]] = {{entry.CONSTRUCTOR_ID: entry for entry in ALL_{module_kind.upper()}}}"
    )
    lines.append(
        f"NAME_MAP: dict[str, type[{base_class}]] = {{entry.QUALNAME: entry for entry in ALL_{module_kind.upper()}}}"
    )
    lines.append(f"__all__ = {tuple(all_names)!r}")
    lines.append("")
    return "\n".join(lines)


def _field_line(field: TLParameter) -> str:
    """Render a generated dataclass field declaration for one public TL parameter.

    Args:
        field: Parsed public TL parameter.
    """
    annotation = _annotation(field)
    if field.is_true_flag:
        return f"    {field.python_name}: bool = False"
    if field.is_optional:
        return f"    {field.python_name}: {annotation} | None = None"
    return f"    {field.python_name}: {annotation}"


def _annotation(field: TLParameter) -> str:
    """Resolve the public Python annotation for a parsed TL parameter.

    Args:
        field: Parsed TL parameter whose type expression is annotated.
    """
    if field.is_vector:
        return f"tuple[{_single_annotation(field.vector_item_type or 'object')}, ...]"
    return _single_annotation(field.type)


def _single_annotation(type_name: str) -> str:
    """Map a non-vector TL type expression to its public Python annotation.

    Args:
        type_name: Normalized or schema-spelled TL type expression.
    """
    clean = type_name.removeprefix("!")
    match clean:
        case "int" | "long" | "int128" | "int256":
            return "int"
        case "double":
            return "float"
        case "string":
            return "str"
        case "bytes":
            return "bytes"
        case "Bool" | "bool" | "true":
            return "bool"
        case "X" | "Type" | "#":
            return "Any"
        case _:
            return "Any"


def _fields_tuple(fields: Sequence[TLParameter]) -> str:
    """Render immutable generated field metadata for generic TL codec fallback.

    Args:
        fields: Public parameters for one generated constructor.
    """
    if not fields:
        return "()"
    lines = ["("]
    for field in fields:
        lines.extend(
            [
                "    TLField(",
                f"        name={field.name!r},",
                f"        python_name={field.python_name!r},",
                f"        type={field.type!r},",
                f"        flag={field.flag!r},",
                f"        flag_index={field.flag_index!r},",
                f"        is_optional={field.is_optional!r},",
                f"        is_true_flag={field.is_true_flag!r},",
                f"        is_vector={field.is_vector!r},",
                f"        vector_item_type={field.vector_item_type!r},",
                "    ),",
            ]
        )
    lines.append(")")
    return "\n".join(lines)


def _flag_groups_tuple(params: Sequence[TLParameter]) -> str:
    """Render generated metadata describing where TL optional-flag words occur.

    Args:
        params: All parsed parameters, including flag markers and templates.
    """
    groups: list[tuple[str, str, int]] = []
    public_index = 0
    for param in params:
        if param.is_flags_marker:
            groups.append((param.name, param.python_name, public_index))
        elif not param.is_template and not param.is_bare:
            public_index += 1
    if not groups:
        return "()"
    lines = ["("]
    for name, python_name, before_field_index in groups:
        lines.extend(
            [
                "    TLFlagGroup(",
                f"        name={name!r},",
                f"        python_name={python_name!r},",
                f"        before_field_index={before_field_index!r},",
                "    ),",
            ]
        )
    lines.append(")")
    return "\n".join(lines)


def _codec_methods(
    fields: Sequence[TLParameter], params: Sequence[TLParameter], *, fast_directions: frozenset[str]
) -> list[str]:
    """Render serialization and deserialization methods for one generated raw class.

    Args:
        params: Parsed parameters for the generated class, including hidden schema markers.
        fields: Public fields derived from ``params`` for generated serialization.
        fast_directions: Reviewed native directions for this class's constructor.
    """
    lines: list[str] = [
        "    def serialize(self) -> bytes:",
        "        return self._serialize(boxed=True)",
        "",
        "    def _serialize(self, *, boxed: bool = True) -> bytes:",
    ]
    if "encode" in fast_directions:
        values = ", ".join(_fast_encode_value(field) for field in fields)
        tuple_suffix = "," if len(fields) == 1 else ""
        lines.extend(
            [
                f"        native = encode_fast(self.CONSTRUCTOR_ID, ({values}{tuple_suffix}), boxed=boxed)",
                "        if native is not None:",
                "            return native",
            ]
        )
    lines.extend(
        [
            "        output = bytearray()",
            "        if boxed:",
            "            output.extend(encode_constructor_id(self.CONSTRUCTOR_ID))",
        ]
    )
    flag_groups = _flag_group_specs(params)
    for _name, python_name, _before_field_index in flag_groups:
        lines.append(f"        {python_name} = 0")
    for field in fields:
        if not field.is_optional or field.flag is None or field.flag_index is None:
            continue
        flag_var = _flag_var(field, flag_groups)
        if field.is_true_flag:
            lines.extend(
                [f"        if self.{field.python_name}:", f"            {flag_var} |= {1 << field.flag_index}"]
            )
        else:
            lines.extend(
                [
                    f"        if self.{field.python_name} is not None:",
                    f"            {flag_var} |= {1 << field.flag_index}",
                ]
            )
    groups_by_index = _flag_groups_by_index(flag_groups)
    for index, field in enumerate(fields):
        for _name, python_name, _before_field_index in groups_by_index.get(index, ()):
            lines.append(f"        output.extend(encode_int({python_name}))")
        if field.is_optional:
            if field.is_true_flag:
                continue
            lines.extend(
                [
                    f"        if self.{field.python_name} is not None:",
                    f"            output.extend({_encode_expr(field, f'self.{field.python_name}')})",
                ]
            )
        else:
            lines.append(f"        output.extend({_encode_expr(field, f'self.{field.python_name}')})")
    for _name, python_name, _before_field_index in groups_by_index.get(len(fields), ()):
        lines.append(f"        output.extend(encode_int({python_name}))")
    lines.extend(
        [
            "        return bytes(output)",
            "",
            "    @classmethod",
            "    def deserialize(cls, data: bytes | memoryview) -> Self:",
            "        obj, offset = cls._deserialize(data)",
            "        if offset != len(data):",
            "            raise TLCodecError('TL object payload has trailing bytes')",
            "        return obj",
            "",
            "    @classmethod",
            "    def _deserialize(",
            "        cls, data: bytes | memoryview, offset: int = 0, *, boxed: bool = True",
            "    ) -> tuple[Self, int]:",
            "        raw_data = data",
        ]
    )
    if "decode" in fast_directions:
        lines.extend(
            [
                "        try:",
                "            native = decode_fast(cls.CONSTRUCTOR_ID, raw_data, offset, boxed=boxed)",
                "        except ValueError as exc:",
                "            if str(exc).startswith('expected constructor '):",
                "                raise TLCodecError(str(exc)) from exc",
                "            raise",
                "        if native is not None:",
                "            values, cursor = native",
                "            return cls(",
            ]
        )
        for index, field in enumerate(fields):
            lines.append(f"                {field.python_name}={_fast_decode_value(field, index)},")
        lines.extend(["            ), cursor"])
    lines.extend(
        [
            "        cursor = offset",
            "        if boxed:",
            "            constructor_id, cursor = decode_constructor_id(raw_data, cursor)",
            "            if constructor_id != cls.CONSTRUCTOR_ID:",
            "                raise TLCodecError(",
            "                    f'expected constructor 0x{cls.CONSTRUCTOR_ID:08x}, got 0x{constructor_id:08x}'",
            "                )",
        ]
    )
    for _name, python_name, _before_field_index in flag_groups:
        lines.append(f"        {python_name} = 0")
    for index, field in enumerate(fields):
        for _name, python_name, _before_field_index in groups_by_index.get(index, ()):
            lines.append(f"        {python_name}, cursor = decode_int(raw_data, cursor)")
        field_var = _field_value_var(field)
        if field.is_optional:
            flag_var = _flag_var(field, flag_groups)
            present_expr = f"bool({flag_var} & {1 << int(field.flag_index or 0)})"
            if field.is_true_flag:
                lines.append(f"        {field_var} = {present_expr}")
                continue
            lines.extend(
                [
                    f"        if {present_expr}:",
                    f"            {field_var}, cursor = {_decode_expr(field)}",
                    "        else:",
                    f"            {field_var} = None",
                ]
            )
        else:
            lines.append(f"        {field_var}, cursor = {_decode_expr(field)}")
    for _name, python_name, _before_field_index in groups_by_index.get(len(fields), ()):
        lines.append(f"        {python_name}, cursor = decode_int(raw_data, cursor)")
    if fields:
        lines.append("        return cls(")
        for field in fields:
            lines.append(f"            {field.python_name}={_field_value_var(field)},")
        lines.extend(["        ), cursor"])
    else:
        lines.append("        return cls(), cursor")
    return lines


def _fast_encode_value(field: TLParameter) -> str:
    """Render one generated fast-path encode expression.

    Args:
        field: Parsed TL parameter to encode through native metadata.
    """
    value = f"self.{field.python_name}"
    clean = field.type.removeprefix("!")
    if field.is_true_flag or field.is_vector or clean in {"int", "long", "bytes", "string"}:
        return value
    return f"encode_value({field.type!r}, {value})"


def _fast_decode_value(field: TLParameter, index: int) -> str:
    """Render one generated fast-path decode expression at a native value index.

    Args:
        field: Parsed TL parameter receiving the decoded value.
        index: Position in the native decoded-values tuple.
    """
    if field.type.removeprefix("!") == "storage.FileType":
        return f"materialize_empty_object(values[{index}])"
    return f"cast({_annotation(field)}, values[{index}])"


def _flag_group_specs(params: Sequence[TLParameter]) -> list[tuple[str, str, int]]:
    """Collect generated optional-flag groups and the public field index they precede.

    Args:
        params: All parsed parameters for one schema entry.
    """
    groups: list[tuple[str, str, int]] = []
    public_index = 0
    for param in params:
        if param.is_flags_marker:
            groups.append((param.name, param.python_name, public_index))
        elif not param.is_template and not param.is_bare:
            public_index += 1
    return groups


def _flag_groups_by_index(groups: Sequence[tuple[str, str, int]]) -> dict[int, tuple[tuple[str, str, int], ...]]:
    """Group optional-flag specifications by generated field position.

    Args:
        groups: Flag name, Python name and insertion-index triples.
    """
    grouped: dict[int, list[tuple[str, str, int]]] = {}
    for group in groups:
        grouped.setdefault(group[2], []).append(group)
    return {index: tuple(items) for index, items in grouped.items()}


def _flag_var(field: TLParameter, groups: Sequence[tuple[str, str, int]]) -> str:
    """Find the generated local variable holding a field's optional-flag word.

    Args:
        field: Optional field referring to a flag group.
        groups: Generated flag-group specifications.
    """
    for name, python_name, _before_field_index in groups:
        if name == field.flag:
            return python_name
    return str(field.flag)


def _field_value_var(field: TLParameter) -> str:
    """Return the generated temporary variable used while deserializing a field.

    Args:
        field: Parsed field that needs a temporary value name.
    """
    return f"_value_{field.python_name}"


def _encode_expr(field: TLParameter, value_expr: str) -> str:
    """Render generic TL serialization code for a generated field value.

    Args:
        field: Parsed field determining the codec operation.
        value_expr: Generated Python expression supplying the value.
    """
    if field.is_vector:
        return f"encode_vector({value_expr}, {field.vector_item_type!r})"
    match field.type:
        case "int" | "#":
            return f"encode_int({value_expr})"
        case "long":
            return f"encode_long({value_expr})"
        case "int128":
            return f"encode_int128({value_expr})"
        case "int256":
            return f"encode_int256({value_expr})"
        case "double":
            return f"encode_double({value_expr})"
        case "bytes":
            return f"encode_bytes({value_expr})"
        case "string":
            return f"encode_string({value_expr})"
        case "Bool" | "bool":
            return f"encode_bool({value_expr})"
        case "true":
            return "b''"
        case _:
            return f"encode_value({field.type!r}, {value_expr})"


def _decode_expr(field: TLParameter) -> str:
    """Render generic TL deserialization code for a generated field value.

    Args:
        field: Parsed field determining the codec operation.
    """
    if field.is_vector:
        return f"decode_vector(raw_data, cursor, {field.vector_item_type!r})"
    match field.type:
        case "int" | "#":
            return "decode_int(raw_data, cursor)"
        case "long":
            return "decode_long(raw_data, cursor)"
        case "int128":
            return "decode_int128(raw_data, cursor)"
        case "int256":
            return "decode_int256(raw_data, cursor)"
        case "double":
            return "decode_double(raw_data, cursor)"
        case "bytes":
            return "decode_bytes(raw_data, cursor)"
        case "string":
            return "decode_string(raw_data, cursor)"
        case "Bool" | "bool":
            return "decode_bool(raw_data, cursor)"
        case "true":
            return "True, cursor"
        case _:
            return f"decode_value({field.type!r}, raw_data, cursor)"


def _namespace_classes(entries: Sequence[Any]) -> tuple[list[str], list[str]]:
    """Render eager namespace alias classes for generated implementation shards.

    Args:
        entries: Schema entries that may share namespaces.
    """
    namespaces: dict[str, list[Any]] = {}
    for entry in entries:
        if entry.namespace is not None:
            namespaces.setdefault(entry.namespace, []).append(entry)
    lines: list[str] = []
    namespace_names: list[str] = []
    for namespace in sorted(namespaces):
        class_name = namespace.replace(".", "_")
        namespace_names.append(class_name)
        lines.append(f"class {class_name}:")
        for entry in sorted(namespaces[namespace], key=lambda item: item.short_name):
            lines.append(f"    {_short_class_name(entry.short_name)} = {entry.python_class_name}")
        lines.extend(["", ""])
    return lines, namespace_names


def _short_class_name(short_name: str) -> str:
    """Convert a schema short name into the exported PascalCase alias.

    Args:
        short_name: Schema-local constructor or method name.
    """
    import re

    parts = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", short_name).replace("_", " ").split()
    return "".join(part[:1].upper() + part[1:] for part in parts)


def _render_errors(database: Mapping[str, Any]) -> str:
    """Render RPC error lookup metadata from pinned error-name, code and method provenance.

    Args:
        database: Pinned Telegram RPC-error names, codes, descriptions and method mappings.
    """
    errors = database.get("errors", {})
    descriptions = database.get("descriptions", {})
    specs: list[tuple[str, int, tuple[str, ...], str]] = []
    for code, named_errors in sorted(errors.items(), key=lambda item: int(item[0])):
        for name, methods in sorted(named_errors.items()):
            specs.append((name, int(code), tuple(sorted(methods)), str(descriptions.get(name, ""))))
    method_map: dict[str, list[str]] = {}
    for name, _code, methods, _description in specs:
        for method in methods:
            method_map.setdefault(method, []).append(name)
    lines: list[str] = [
        _HEADER.rstrip(),
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        "class RawRPCErrorSpec:",
        "    name: str",
        "    code: int",
        "    methods: tuple[str, ...] = ()",
        "    description: str = ''",
        "",
        "",
        "RPC_ERROR_MAP: dict[tuple[str, int], RawRPCErrorSpec] = {",
    ]
    for name, code, methods, description in specs:
        lines.extend(
            [
                f"    ({name!r}, {code!r}): RawRPCErrorSpec(",
                f"        name={name!r},",
                f"        code={code!r},",
                "        methods=",
                _tuple_literal(methods, indent="        ") + ",",
                f"        description={description!r},",
                "    ),",
            ]
        )
    lines.extend(["}", "CODE_TO_ERROR_NAMES: dict[int, tuple[str, ...]] = {"])
    for code in sorted({code for _name, code, _methods, _description in specs}):
        names = tuple(name for name, item_code, _methods, _description in specs if item_code == code)
        lines.append(f"    {code!r}: {_tuple_literal(names, indent='    ')},")
    lines.extend(["}", "METHOD_TO_ERROR_NAMES: dict[str, tuple[str, ...]] = {"])
    for method in sorted(method_map):
        lines.append(f"    {method!r}: {_tuple_literal(tuple(sorted(set(method_map[method]))), indent='    ')},")
    lines.extend(
        [
            "}",
            "",
            "",
            "def rpc_error_for_name(name: str, code: int | None = None) -> RawRPCErrorSpec | None:",
            "    if code is not None:",
            "        return RPC_ERROR_MAP.get((name, code))",
            "    matches = sorted(",
            "        (error for (error_name, _code), error in RPC_ERROR_MAP.items() if error_name == name),",
            "        key=lambda error: error.code,",
            "    )",
            "    return matches[0] if matches else None",
            "",
            "",
            "def rpc_errors_for_name(name: str) -> tuple[RawRPCErrorSpec, ...]:",
            "    return tuple(",
            "        sorted(",
            "            (error for (error_name, _code), error in RPC_ERROR_MAP.items() if error_name == name),",
            "            key=lambda error: error.code,",
            "        )",
            "    )",
            "",
            "",
            "__all__ = (",
            "    'CODE_TO_ERROR_NAMES',",
            "    'METHOD_TO_ERROR_NAMES',",
            "    'RPC_ERROR_MAP',",
            "    'RawRPCErrorSpec',",
            "    'rpc_error_for_name',",
            "    'rpc_errors_for_name',",
            ")",
            "",
        ]
    )
    return "\n".join(lines)


def _render_telegram_bindings(schema: TLSchema, database: Mapping[str, Any], *, layer: int) -> str:
    """Render exact public Python bindings for static Telegram reference generation.

    Args:
        schema: Parsed canonical constructors and methods whose public raw facades are generated.
        database: Pinned RPC-error names and codes used to derive public exception classes.
        layer: Selected canonical Telegram layer shared by the generated raw surface.

    Returns:
        Deterministic JSON manifest with one record per declaration and pinned RPC error.
    """
    declarations = [
        _telegram_declaration_binding(entry, kind="type", module="miniproto.raw.types") for entry in schema.constructors
    ]
    declarations.extend(
        _telegram_declaration_binding(entry, kind="function", module="miniproto.raw.functions")
        for entry in schema.functions
    )
    errors = database.get("errors", {})
    if not isinstance(errors, Mapping):
        raise TypeError("RPC error database errors must be an object")
    error_bindings = [
        _telegram_error_binding(name, int(code))
        for code, named_errors in errors.items()
        if isinstance(named_errors, Mapping)
        for name in named_errors
    ]
    return _json_document(
        {
            "schema_version": 1,
            "layer": layer,
            "declarations": sorted(
                declarations, key=lambda item: (item["kind"], item["qualified_name"], item["constructor_id"])
            ),
            "errors": sorted(error_bindings, key=lambda item: (item["code"], item["name"])),
        }
    )


def _telegram_declaration_binding(entry: Any, *, kind: str, module: str) -> dict[str, str]:
    """Build one exact public raw-facade binding record without loading generated modules.

    Args:
        entry: Parsed canonical constructor or method with generated Python naming metadata.
        kind: Documentation declaration kind, either ``"type"`` or ``"function"``.
        module: Public raw facade module that exposes the generated class.

    Returns:
        JSON-ready record keyed by kind, exact TL qualified name and normalized constructor ID.
    """
    python_name = str(entry.python_class_name)
    return {
        "kind": kind,
        "qualified_name": str(entry.name),
        "constructor_id": f"0x{int(entry.constructor_id):08x}",
        "python_module": module,
        "python_name": python_name,
        "python_import": f"from {module} import {python_name}",
        "public_access": f"{module}.{python_name}",
    }


def _telegram_error_binding(name: object, code: int) -> dict[str, str | int]:
    """Build one exact public dynamically generated RPC-error class binding record.

    Args:
        name: Pinned symbolic RPC error template.
        code: Pinned numeric RPC error code.

    Returns:
        JSON-ready public ``miniproto.errors`` import record.

    Raises:
        TypeError: If the pinned error name is not a string.
    """
    if not isinstance(name, str):
        raise TypeError("RPC error names must be strings")
    module = "miniproto.errors"
    python_name = _telegram_error_class_name(name)
    return {
        "code": code,
        "name": name,
        "python_module": module,
        "python_name": python_name,
        "python_import": f"from {module} import {python_name}",
        "public_access": f"{module}.{python_name}",
    }


def _telegram_error_class_name(name: str) -> str:
    """Mirror the runtime's generated public RPC-error class-name contract.

    Args:
        name: Canonical Telegram RPC error template from the pinned database.

    Returns:
        Importable public class name used by ``miniproto.errors``.
    """
    cleaned = re.sub(r"%d", "", name, flags=re.IGNORECASE).strip("_")
    parts = [part for part in re.split(r"[^0-9A-Za-z]+", cleaned) if part]
    if not parts:
        return "UnknownRpcError"
    rendered = "".join(_telegram_error_class_name_part(part) for part in parts)
    return f"Rpc{rendered}" if rendered[0].isdigit() else rendered


def _telegram_error_class_name_part(part: str) -> str:
    """Render one symbolic RPC-error component using the runtime capitalization rule.

    Args:
        part: Alphanumeric component from a Telegram symbolic error name.

    Returns:
        One normalized public Python class-name component.
    """
    if part.upper() == "2FA":
        return "TwoFa"
    if part.isdigit():
        return part
    return part[:1].upper() + part[1:].lower()


def _tuple_literal(values: Sequence[str], *, indent: str) -> str:
    """Render a deterministic Python tuple literal with the requested indentation.

    Args:
        values: String values to quote in the literal.
        indent: Existing indentation to apply to multiline closing and item lines.
    """
    if not values:
        return "()"
    if len(values) == 1:
        return f"({values[0]!r},)"
    inner = ["("]
    inner.extend(f"{indent}    {value!r}," for value in values)
    inner.append(f"{indent})")
    return "\n".join(inner)


def _load_rpc_error_database(path: Path) -> Mapping[str, Any]:
    """Load a pinned RPC-error JSON object or use an empty database when absent.

    Args:
        path: Pinned RPC-error JSON path.
    """
    if not path.exists():
        return {"errors": {}, "descriptions": {}}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("RPC error database must be a JSON object")
    return data


def _load_existing_metadata(path: Path) -> Mapping[str, Any]:
    """Load prior generated metadata needed to preserve update provenance, if present.

    Args:
        path: Prior generated metadata JSON path.
    """
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("schema metadata must be a JSON object")
    return data


def _sha256_file(path: Path) -> str:
    """Return the SHA-256 digest of a pinned source file.

    Args:
        path: Source file to hash.
    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _json_document(data: Mapping[str, Any]) -> str:
    """Render deterministic pretty JSON with a final newline.

    Args:
        data: Mapping to serialize with sorted keys.
    """
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


