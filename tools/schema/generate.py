@dataclass(frozen=True, slots=True)
class GeneratedOutputs:
    """Complete generated-file content plus directories whose stale generated shards are owned.

    Attributes:
        files: Mapping from each generated destination path to its complete, formatter-normalized expected text.
        owned_directories: Shard directories whose header-marked generated ``.py`` files may be removed when absent from ``files``; defaults to an empty tuple.
    """

    files: Mapping[Path, str]
    owned_directories: tuple[Path, ...] = ()


def main(argv: Sequence[str] | None = None) -> int:
    """Run schema generation or its non-mutating freshness check.

    Args:
        argv: Optional CLI arguments; defaults to process arguments.

    Returns:
        ``0`` when generation succeeds or all artifacts are fresh; ``1`` for stale ``--check`` output.
    """
    parser = argparse.ArgumentParser(description="Generate miniproto raw API modules from pinned TL schema.")
    parser.add_argument("--schema", type=Path, default=_DEFAULT_SCHEMA, help="pinned canonical TL schema input to read")
    parser.add_argument(
        "--metadata",
        type=Path,
        default=_DEFAULT_METADATA,
        help="schema provenance and generated-artifact manifest JSON to create or check",
    )
    parser.add_argument(
        "--errors", type=Path, default=_DEFAULT_ERRORS, help="pinned Telegram RPC-error database JSON to read"
    )
    parser.add_argument(
        "--telegram-bindings",
        type=Path,
        default=_DEFAULT_TELEGRAM_BINDINGS,
        help="static public raw-binding manifest JSON to create or check",
    )
    parser.add_argument(
        "--raw-dir",
        type=Path,
        default=_DEFAULT_RAW_DIR,
        help="owned generated Python raw API tree to reconcile or check",
    )
    parser.add_argument(
        "--rust-fast-manifest",
        type=Path,
        default=_DEFAULT_RUST_FAST_MANIFEST,
        help="reviewed Rust TL fast-path manifest JSON whose schema pins are refreshed",
    )
    parser.add_argument(
        "--generated-rust",
        type=Path,
        default=_DEFAULT_GENERATED_RUST,
        help="owned generated Rust TL fast-path source to create or check",
    )
    parser.add_argument(
        "--fast-metadata",
        type=Path,
        default=_DEFAULT_FAST_METADATA,
        help="owned generated Python TL fast-path metadata module to create or check",
    )
    parser.add_argument("--check", action="store_true", help="fail when generated files or metadata are stale")
    args = parser.parse_args(argv)
    outputs = render_outputs(
        args.schema,
        args.metadata,
        args.errors,
        args.raw_dir,
        args.rust_fast_manifest,
        args.generated_rust,
        args.fast_metadata,
        args.telegram_bindings,
    )
    stale = stale_outputs(outputs)
    if args.check:
        if stale:
            for path in stale:
                print(f"stale generated file: {path}")
            return 1
        print("schema generated files are fresh")
        return 0
    write_outputs(outputs)
    return 0


def render_outputs(
    schema_path: Path = _DEFAULT_SCHEMA,
    metadata_path: Path = _DEFAULT_METADATA,
    errors_path: Path = _DEFAULT_ERRORS,
    raw_dir: Path = _DEFAULT_RAW_DIR,
    rust_fast_manifest_path: Path | None = None,
    generated_rust_path: Path | None = None,
    fast_metadata_path: Path | None = None,
    telegram_bindings_path: Path | None = None,
) -> GeneratedOutputs:
    """Render every deterministic artifact from pinned schema, metadata and error inputs.

    Args:
        schema_path: Normalized TL schema JSON source.
        metadata_path: Generated schema metadata destination and existing metadata input.
        errors_path: Pinned Telegram RPC-error database.
        raw_dir: Root directory for generated raw Python modules and shards.
        rust_fast_manifest_path: Optional reviewed fast-path manifest whose schema pins are refreshed.
        generated_rust_path: Optional generated Rust fast-path destination.
        fast_metadata_path: Optional generated Python fast-path metadata destination.
        telegram_bindings_path: Optional generated static raw-Python binding manifest destination.

    Returns:
        Expected content for every generated output and owned shard directory.
    """
    schema = parse_schema_file(schema_path)
    rpc_error_database = _load_rpc_error_database(errors_path)
    metadata = _metadata(schema_path, errors_path, metadata_path, schema, rpc_error_database)
    binding_manifest_path = telegram_bindings_path or metadata_path.with_name("telegram-bindings.json")
    fast_manifest = (
        render_fast_manifest(rust_fast_manifest_path, schema_path, int(metadata["schema_layer"]))
        if rust_fast_manifest_path is not None
        else None
    )
    fast_entries = (
        load_fast_entries(
            rust_fast_manifest_path, schema_path, int(metadata["schema_layer"]), schema, manifest_text=fast_manifest
        )
        if rust_fast_manifest_path is not None
        else ()
    )
    fast_directions = fast_api_directions(fast_entries)
    type_shard_dir = raw_dir / "_types_shards"
    function_shard_dir = raw_dir / "_function_shards"
    files: dict[Path, str] = {
        metadata_path: _json_document(metadata),
        raw_dir / "base.py": _render_base(metadata),
        raw_dir / "types.py": _render_facade(schema.constructors, module_kind="types"),
        raw_dir / "types.pyi": _render_stub(schema.constructors, module_kind="types"),
        raw_dir / "functions.py": _render_facade(schema.functions, module_kind="functions"),
        raw_dir / "functions.pyi": _render_stub(schema.functions, module_kind="functions"),
        raw_dir / "_registry.py": _render_registry(schema),
        raw_dir / "errors.py": _render_errors(rpc_error_database),
        binding_manifest_path: _render_telegram_bindings(
            schema, rpc_error_database, layer=int(metadata["schema_layer"])
        ),
    }
    if generated_rust_path is not None and fast_metadata_path is not None:
        files[generated_rust_path] = render_rust(
            fast_entries, int(metadata["schema_layer"]), str(metadata["schema_json_sha256"])
        )
        files[fast_metadata_path] = render_python_metadata(
            fast_entries, int(metadata["schema_layer"]), str(metadata["schema_json_sha256"])
        )
    if rust_fast_manifest_path is not None and fast_manifest is not None:
        files[rust_fast_manifest_path] = fast_manifest
    files.update(
        _render_shards(
            schema.constructors,
            module_kind="types",
            shard_dir=type_shard_dir,
            bucket_count=_TYPE_BUCKET_COUNT,
            fast_directions=fast_directions,
        )
    )
    files.update(
        _render_shards(
            schema.functions,
            module_kind="functions",
            shard_dir=function_shard_dir,
            bucket_count=_FUNCTION_BUCKET_COUNT,
            fast_directions=fast_directions,
        )
    )
    formatted = {
        path: (
            _format_python(path, content)
            if path.suffix in {".py", ".pyi"}
            else _format_rust(path, content)
            if path.suffix == ".rs"
            else content
        )
        for path, content in files.items()
    }
    return GeneratedOutputs(files=formatted, owned_directories=(type_shard_dir, function_shard_dir))


def write_outputs(outputs: GeneratedOutputs) -> None:
    """Reconcile owned generated files and remove obsolete owned shard files.

    Args:
        outputs: Expected content and owned directories from :func:`render_outputs`.
    """
    for path in _unexpected_owned_outputs(outputs):
        path.unlink()
    for path, content in outputs.files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def stale_outputs(outputs: GeneratedOutputs) -> tuple[Path, ...]:
    """Return expected outputs that are missing, differ or are obsolete owned shards.

    Args:
        outputs: Expected content and owned directories from :func:`render_outputs`.
    """
    stale: list[Path] = []
    for path, expected in outputs.files.items():
        if not path.exists() or not _matches_generated_output(path, path.read_text(encoding="utf-8"), expected):
            stale.append(path)
    stale.extend(_unexpected_owned_outputs(outputs))
    return tuple(stale)


def _matches_generated_output(path: Path, actual: str, expected: str) -> bool:
    """Compare generated output while tolerating one retired handwritten-doc manifest entry.

    Existing schema metadata may still record ``docs/raw-api.md`` from before
    documentation became handwritten. The generator no longer owns that file,
    so ``--check`` ignores only that exact legacy manifest member; every other
    metadata or output difference remains stale.

    Args:
        path: Generated destination whose current content is being checked.
        actual: Existing UTF-8 content from the working tree.
        expected: Newly rendered UTF-8 content for the destination.
    """
    if actual == expected:
        return True
    if path.name != "schema-metadata.json":
        return False
    try:
        actual_metadata = json.loads(actual)
        expected_metadata = json.loads(expected)
    except ValueError:
        return False
    if not isinstance(actual_metadata, dict) or not isinstance(expected_metadata, dict):
        return False
    manifest = actual_metadata.get("generated_file_manifest")
    if not isinstance(manifest, list):
        return False
    actual_metadata["generated_file_manifest"] = [
        entry for entry in manifest if entry != _LEGACY_HANDWRITTEN_DOC_MANIFEST_ENTRY
    ]
    return actual_metadata == expected_metadata


def _unexpected_owned_outputs(outputs: GeneratedOutputs) -> tuple[Path, ...]:
    """Find generated shard files in owned directories that this render no longer expects.

    Args:
        outputs: Expected content and the directories whose generated shards are owned.
    """
    expected = frozenset(outputs.files)
    unexpected: list[Path] = []
    for directory in outputs.owned_directories:
        if not directory.exists():
            continue
        for path in directory.glob("*.py"):
            if path in expected:
                continue
            if path.read_text(encoding="utf-8").startswith(_HEADER.splitlines()[0]):
                unexpected.append(path)
    return tuple(sorted(unexpected))


def _bucket_for_constructor_id(constructor_id: int, bucket_count: int) -> int:
    """Map a constructor ID to its deterministic power-of-two shard bucket.

    Args:
        constructor_id: Unsigned TL constructor identifier.
        bucket_count: Positive power-of-two shard count.

    Raises:
        ValueError: ``bucket_count`` is not a positive power of two.
    """
    if bucket_count <= 0 or bucket_count & (bucket_count - 1):
        raise ValueError("bucket_count must be a positive power of two")
    return constructor_id & (bucket_count - 1)


def _render_shards(
    entries: Sequence[Any],
    *,
    module_kind: str,
    shard_dir: Path,
    bucket_count: int,
    fast_directions: Mapping[int, frozenset[str]],
) -> dict[Path, str]:
    """Partition schema entries by constructor ID and render one Python module per bucket.

    Args:
        entries: Constructor or function schema entries.
        module_kind: Generated raw surface kind, ``"types"`` or ``"functions"``.
        shard_dir: Destination directory for generated shard modules.
        bucket_count: Positive power-of-two number of shard buckets.
        fast_directions: Reviewed native fast-path directions by constructor ID.
    """
    buckets: dict[int, list[Any]] = {}
    for entry in entries:
        bucket = _bucket_for_constructor_id(entry.constructor_id, bucket_count)
        buckets.setdefault(bucket, []).append(entry)
    return {
        shard_dir / f"bucket_{bucket:02d}.py": _render_entries_module(
            tuple(bucket_entries), module_kind=module_kind, fast_directions=fast_directions
        )
        for bucket, bucket_entries in sorted(buckets.items())
    }


def _render_facade(entries: Sequence[Any], *, module_kind: str) -> str:
    """Render a lazy public raw-type or raw-function facade module.

    Args:
        entries: Schema entries exposed from the facade.
        module_kind: Facade kind, ``"types"`` or ``"functions"``.
    """
    collection_name = f"ALL_{module_kind.upper()}"
    public_names = [entry.python_class_name for entry in entries]
    namespaces = sorted({entry.namespace for entry in entries if entry.namespace is not None})
    namespace_names = [namespace.replace(".", "_") for namespace in namespaces]
    lines = [
        _HEADER.rstrip(),
        "from __future__ import annotations",
        "",
        "from miniproto.raw._registry import (",
        "    LazyClassSequence,",
        "    LazyConstructorMap,",
        "    LazyNameMap,",
        "    lazy_namespace,",
        "    resolve_class,",
        ")",
        "",
        "",
    ]
    for namespace, public_name in zip(namespaces, namespace_names, strict=True):
        lines.append(f"{public_name} = lazy_namespace({module_kind!r}, {namespace!r})")
    if namespaces:
        lines.append("")
    lines.extend(
        [
            f"{collection_name} = LazyClassSequence({module_kind!r})",
            f"CONSTRUCTOR_ID_MAP = LazyConstructorMap({module_kind!r})",
            f"NAME_MAP = LazyNameMap({module_kind!r})",
            "",
            "",
            "def __getattr__(name: str):",
            f"    resolved = resolve_class({module_kind!r}, name)",
            "    globals()[name] = resolved",
            "    return resolved",
            "",
            "",
            "def __dir__():",
            f"    return sorted(set(globals()).union({tuple(public_names)!r}))",
            "",
            "",
            f"__all__ = {tuple(public_names + namespace_names + ['CONSTRUCTOR_ID_MAP', 'NAME_MAP'])!r}",
            "",
        ]
    )
    return "\n".join(lines)


def _render_stub(entries: Sequence[Any], *, module_kind: str) -> str:
    """Render static declarations for a lazy raw facade without importing its shards.

    Args:
        entries: Schema entries declared in the stub.
        module_kind: Facade kind used to choose its base class.
    """
    base_class = "TLConstructor" if module_kind == "types" else "TLRequest"
    lines = [
        _HEADER.rstrip(),
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping, Sequence",
        "from typing import Any, ClassVar",
        "",
        f"from miniproto.raw.base import {base_class}",
        "",
        "",
    ]
    for entry in entries:
        fields = iter_public_params(entry.params)
        lines.extend(
            [
                f"class {entry.python_class_name}({base_class}):",
                "    CONSTRUCTOR_ID: ClassVar[int]",
                "    QUALNAME: ClassVar[str]",
                "    RESULT_TYPE: ClassVar[str]",
            ]
        )
        for field in fields:
            lines.append(f"    {field.python_name}: {_stub_annotation(field)}")
        parameters = ["self"]
        if fields:
            parameters.append("*")
            for field in fields:
                default = " = ..." if field.is_optional else ""
                parameters.append(f"{field.python_name}: {_stub_annotation(field)}{default}")
        lines.extend([f"    def __init__({', '.join(parameters)}) -> None: ...", "", ""])
    namespace_lines, _namespace_names = _namespace_classes(entries)
    lines.extend(namespace_lines)
    lines.extend(
        [
            f"ALL_{module_kind.upper()}: Sequence[type[{base_class}]]",
            f"CONSTRUCTOR_ID_MAP: Mapping[int, type[{base_class}]]",
            f"NAME_MAP: Mapping[str, type[{base_class}]]",
            "__all__: tuple[str, ...]",
            "",
        ]
    )
    return "\n".join(lines)


def _stub_annotation(field: TLParameter) -> str:
    """Return the public type annotation for one generated stub field.

    Args:
        field: Parsed TL parameter to annotate.
    """
    annotation = _annotation(field)
    return f"{annotation} | None" if field.is_optional and not field.is_true_flag else annotation


