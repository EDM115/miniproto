    schema_layer = int(previous.get("schema_layer", previous.get("layer", _SCHEMA_LAYER)))
    rpc_error_layer = rpc_error_database.get("layer", previous.get("rpc_error_layer"))
    schema_sha256 = _sha256_file(schema_path)
    metadata = dict(previous)
    metadata.update(
        {
            "layer": schema_layer,
            "schema_layer": schema_layer,
            "changelog_latest_layer": previous.get("changelog_latest_layer"),
            "canonical_source": previous.get("canonical_source", "tdlib"),
            "source_url": previous.get("source_url", _SOURCE_SCHEMA_URL),
            "schema_source_url": previous.get("schema_source_url", _SOURCE_SCHEMA_URL),
            "structural_source_url": previous.get("structural_source_url", _SOURCE_SCHEMA_URL),
            "layer_source_url": previous.get("layer_source_url", _SOURCE_LAYER_URL),
            "schema_doc_url": previous.get("schema_doc_url", _SOURCE_SCHEMA_DOC_URL),
            "source_note": previous.get(
                "source_note",
                "Canonical structure is the pinned TDLib TL schema; the layer comes from the matching Telegram Desktop end-of-file marker.",
            ),
            "documentation_merge_precedence": previous.get(
                "documentation_merge_precedence", ["tdlib", "tdesktop", "core_json"]
            ),
            "fetch_date": previous.get("fetch_date", "unknown"),
            "sha256": schema_sha256,
            "schema_sha256": schema_sha256,
            "schema_json_sha256": schema_sha256 if schema_format == "json" else previous.get("schema_json_sha256"),
            "schema_tl_sha256": previous.get("schema_tl_sha256"),
            "schema_tl_source_kind": previous.get("schema_tl_source_kind"),
            "schema_format": schema_format,
            "generator_version": _GENERATOR_VERSION,
            "constructor_count": len(schema.constructors),
            "function_count": len(schema.functions),
            "rpc_error_source_url": _SOURCE_ERRORS_URL,
            "rpc_error_download_url": previous.get("rpc_error_download_url", _SOURCE_ERRORS_DOWNLOAD_URL),
            "rpc_error_layer": rpc_error_layer,
            "rpc_error_sha256": _sha256_file(errors_path),
            "rpc_error_count": error_count,
            "changelog_source_url": previous.get("changelog_source_url", _SOURCE_CHANGELOG_URL),
            "generated_file_manifest": list(_MANIFEST),
        }
    )
    return metadata


