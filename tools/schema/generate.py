def _render_source_comparison_docs(metadata: Mapping[str, Any]) -> str:
    paragraphs = [
        "The complete deterministic declaration-level comparison is pinned at `tools/schema/schema-source-diff.json`."
    ]
    summary = metadata.get("source_comparison_summary")
    if not isinstance(summary, Mapping):
        return "\n\n".join(paragraphs)
    desktop = summary.get("tdlib_vs_tdesktop")
    if isinstance(desktop, Mapping):
        tdlib_only = desktop.get("tdlib_only", ())
        tdesktop_only = desktop.get("tdesktop_only", ())
        tdlib_only_count = len(tdlib_only)
        tdesktop_only_count = len(tdesktop_only)
        tdlib_names = ", ".join(f"`{name}`" for name in tdlib_only)
        tdesktop_names = ", ".join(f"`{name}`" for name in tdesktop_only)
        paragraph = (
            f"TDLib and Telegram Desktop overlap on {desktop.get('overlap_count', 'unknown')} declarations with "
            f"{desktop.get('changed_count', 'unknown')} structural differences. TDLib contributes {tdlib_only_count} additional {'declaration' if tdlib_only_count == 1 else 'declarations'}"
        )
        if tdlib_names:
            paragraph += f": {tdlib_names}"
        paragraph += f". Telegram Desktop contributes {tdesktop_only_count} {'declaration' if tdesktop_only_count == 1 else 'declarations'} absent from canonical TDLib"
        if tdesktop_names:
            paragraph += f": {tdesktop_names}"
        paragraph += "."
        if "null" in tdesktop_only:
            paragraph += f" Because `null` is absent from canonical TDLib, the previously generated `Null` class is intentionally absent from Layer {metadata.get('schema_layer', 'unknown')} outputs."
        paragraphs.append(paragraph)
    core = summary.get("tdlib_vs_core")
    if isinstance(core, Mapping):
        paragraphs.append(
            f"The supporting core schema overlaps on {core.get('overlap_count', 'unknown')} declarations, has {core.get('changed_count', 'unknown')} changed declarations, {core.get('tdlib_only_count', 'unknown')} TDLib-only declarations, and {core.get('core_only_count', 'unknown')} core-only declarations. These differences are drift evidence only."
        )
    return "\n\n".join(paragraphs)


def _load_rpc_error_database(path: Path) -> Mapping[str, Any]:
    if not path.exists():
        return {"errors": {}, "descriptions": {}}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("RPC error database must be a JSON object")
    return data


def _load_existing_metadata(path: Path) -> Mapping[str, Any]:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("schema metadata must be a JSON object")
    return data


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _json_document(data: Mapping[str, Any]) -> str:
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


